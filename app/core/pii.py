"""Маскировка персональных данных в тексте: телефоны, почты, номера карт.

Используется и в импорте переписки, и в журнале диалогов: клиент может сам
написать в чат телефон или почту, хранить их в журнале незачем.
"""
from __future__ import annotations

import re

# +7 912 345-67-89, 8(912)3456789, а также 912 345-67-89 без кода страны (мобильные на 9)
_PHONE_RE = re.compile(
    r"(?<!\d)(?:(?:\+7|8)[\s\-(]*\d{3}|9\d{2})[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)"
)
_EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")
_CARD_RE = re.compile(r"\b(?:\d[ -]?){16}\b")


def mask_pd(text: str) -> str:
    """Скрыть персональные данные: телефоны, почты, номера карт."""
    text = _CARD_RE.sub("[карта]", text)
    text = _PHONE_RE.sub("[телефон]", text)
    return _EMAIL_RE.sub("[почта]", text)
